function interpolate(value: string, values?: Record<string, string | number>) {
  if (!values) return value;
  return value.replace(/\{(\w+)\}/g, (match, key: string) => String(values[key] ?? match));
}

function getLanguageSnapshot(): Language {
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    if (saved === "ka" || saved === "en" || saved === "ru") return saved;
  } catch (error) {
    console.error("Could not read the saved language preference", error);
  }
  return currentLanguage;
}

function subscribeToLanguage(onChange: () => void) {
  window.addEventListener("storage", onChange);
  window.addEventListener(LANGUAGE_EVENT, onChange);
  return () => {
    window.removeEventListener("storage", onChange);
    window.removeEventListener(LANGUAGE_EVENT, onChange);
  };
}

function getServerLanguage(): Language {
  return "ka";
}

export function I18nProvider({ children }: Readonly<{ children: React.ReactNode }>) {
  const language = useSyncExternalStore<Language>(subscribeToLanguage, getLanguageSnapshot, getServerLanguage);
  const pathname = usePathname();

  useEffect(() => {
    document.documentElement.lang = language;
    const titleKey: TranslationKey = pathname === "/terms"
      ? "legal.terms.title"
      : pathname === "/privacy"
        ? "legal.privacy.title"
        : pathname === "/admin"
          ? "admin.title"
          : "header.season";
    const title = titleKey === "header.season"
      ? language === "ka"
        ? "World Market — ქართული ონლაინ მარკეტპლეისი"
        : language === "en"
          ? "World Market — Georgian online marketplace"
          : "World Market — грузинский онлайн-маркетплейс"
      : `${dictionary[language][titleKey]} | World Market`;
    document.title = title;
  }, [language, pathname]);

  const value = useMemo<LanguageContextValue>(() => ({
    language,
    setLanguage: (nextLanguage) => {
      currentLanguage = nextLanguage;
      try {
        window.localStorage.setItem(STORAGE_KEY, nextLanguage);
      } catch (error) {
        console.error("Could not save the language preference", error);
      }
      window.dispatchEvent(new Event(LANGUAGE_EVENT));
    },
    t: (key, values) => interpolate(dictionary[language][key], values),
    translateServerMessage: (message) => {
      if (!message) return message;
      const key = commonServerMessages[message] || (language === "ka" ? undefined : serverMessages[language][message]);
      return key ? interpolate(dictionary[language][key]) : message;
    },
    categoryName: (category) => language === "ka"
      ? category.nameKa
      : categoryNames[language][category.slug || ""] || category.nameEn,
    conditionName: (condition) => {
      const keys: Record<string, TranslationKey> = {
        NEW: "listing.condition.new",
        LIKE_NEW: "listing.condition.likeNew",
        GOOD: "listing.condition.good",
        FAIR: "listing.condition.fair"
      };
      return keys[condition] ? interpolate(dictionary[language][keys[condition]]) : condition;
    },
    statusName: (status) => {
      const keys: Record<string, TranslationKey> = {
        ACTIVE: "listing.status.active",
        PAUSED: "listing.status.paused",
        RESERVED: "listing.status.reserved",
        SOLD: "listing.status.sold",
        REMOVED: "listing.status.removed"
      };
      return keys[status] ? interpolate(dictionary[language][keys[status]]) : status;
    }
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useI18n() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useI18n must be used within I18nProvider");
  return context;
}
